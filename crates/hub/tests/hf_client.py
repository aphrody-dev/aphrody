import os, sys, tempfile, json
from huggingface_hub import HfApi, hf_hub_download, snapshot_download
api = HfApi(endpoint=os.environ["HF_ENDPOINT"], token="tok")
res = {}
def t(name, f):
    try: res[name] = ("ok", str(f())[:120])
    except Exception as e: res[name] = ("FAIL", repr(e)[:300])
t("whoami", lambda: api.whoami()["name"])
t("create_repo", lambda: api.create_repo("alice/m1", exist_ok=True))
d = tempfile.mkdtemp()
open(d+"/a.txt","w").write("hello")
open(d+"/big.bin","wb").write(os.urandom(300000))
t("upload_file", lambda: api.upload_file(path_or_fileobj=d+"/a.txt", path_in_repo="a.txt", repo_id="alice/m1"))
t("upload_folder", lambda: api.upload_folder(folder_path=d, repo_id="alice/m1", path_in_repo="sub"))
t("model_info", lambda: [s.rfilename for s in api.model_info("alice/m1").siblings])
t("list_files", lambda: api.list_repo_files("alice/m1"))
t("download", lambda: open(hf_hub_download("alice/m1","a.txt",cache_dir=d+"/c")).read())
t("download_lfs", lambda: os.path.getsize(hf_hub_download("alice/m1","sub/big.bin",cache_dir=d+"/c")))
t("snapshot", lambda: os.listdir(snapshot_download("alice/m1",cache_dir=d+"/c2")))
t("list_models", lambda: [m.id for m in api.list_models(search="m1", limit=5)])
t("commits", lambda: len(api.list_repo_commits("alice/m1")))
t("refs", lambda: api.list_repo_refs("alice/m1").branches)
t("file_exists", lambda: api.file_exists("alice/m1","a.txt"))
t("delete_file", lambda: api.delete_file("a.txt","alice/m1"))
for k,v in res.items(): print(k, *v)

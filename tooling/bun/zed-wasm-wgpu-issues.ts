export function serializeLedgerToml(): string {
  const lines: string[] = [
    "# Auto-generated by tooling/bun/zed-wasm-wgpu-issues.ts audit — do not hand-edit.",
    "schema_version = 1",
    `purged_legacy_python_scripts = ${PURGED_LEGACY_SCRIPTS.length}`,
    `tracked_wasm_wgpu_issues = ${WASM_WGPU_ISSUES.length}`,
    `purged_scripts = [${PURGED_LEGACY_SCRIPTS.map((s) => JSON.stringify(s)).join(", ")}]`,
    "",
  ];
  for (const issue of WASM_WGPU_ISSUES) {
    lines.push("[[issues]]");
    lines.push(`id = ${JSON.stringify(issue.id)}`);
    lines.push(`upstream = ${JSON.stringify(issue.upstream)}`);
    lines.push(`domain = ${JSON.stringify(issue.domain)}`);
    lines.push(`title = ${JSON.stringify(issue.title)}`);
    lines.push(`status = ${JSON.stringify(issue.status)}`);
    lines.push(`crate_paths = [${issue.crate_paths.map((p) => JSON.stringify(p)).join(", ")}]`);
    lines.push(`resolution = ${JSON.stringify(issue.resolution)}`);
    lines.push("");
  }
  return lines.join("\n");
}

export function auditWorkspace(
  root = repoRoot,
  outPath = DEFAULT_LEDGER_PATH,
  writeLedger = true,
): { ok: boolean; remainingLegacyScripts: string[]; missingCratePaths: string[]; totalIssues: number } {
  const remainingLegacyScripts = PURGED_LEGACY_SCRIPTS.filter((rel) => existsSync(join(root, rel)));
  const missingCratePaths: string[] = [];
  for (const issue of WASM_WGPU_ISSUES) {
    for (const rel of issue.crate_paths) {
      if (!existsSync(join(root, rel))) missingCratePaths.push(`${issue.id}:${rel}`);
    }
  }
  if (writeLedger) {
    mkdirSync(resolve(outPath, ".."), { recursive: true });
    writeFileSync(outPath, serializeLedgerToml(), "utf8");
  }
  return {
    ok: remainingLegacyScripts.length === 0 && missingCratePaths.length === 0,
    remainingLegacyScripts,
    missingCratePaths,
    totalIssues: WASM_WGPU_ISSUES.length,
  };
}

if (import.meta.main) {
  const args = Bun.argv.slice(2);
  const outIdx = args.indexOf("--out");
  const outPath = outIdx >= 0 && args[outIdx + 1] ? resolve(repoRoot, args[outIdx + 1]) : DEFAULT_LEDGER_PATH;
  const report = auditWorkspace(repoRoot, outPath, true);
  console.log(JSON.stringify({ ledger: outPath, ...report }, null, 2));
  if (!report.ok) process.exit(1);
}

// Target registry: what Aphrody can target, read from the reference sources instead of hand-picked lists.
//   programming languages  GitHub Linguist languages.yml (type programming)
//   human languages        Unicode CLDR availableLocales (full set)
//   OS / arch              rustc --print target-list, go tool dist list, zig targets, Bun compile targets (bun-types)
//   UI frameworks          docs/ideas/inventory/frameworks.json (registries + GitHub)
// Output: docs/ideas/inventory/targets.{json,md}. A tool that is not installed is reported, not guessed.
// bun scripts/inventory/targets.ts
import { existsSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "../..");
const sh = (cmd: string[]) => {
  try {
    const r = Bun.spawnSync(cmd, { stdout: "pipe", stderr: "pipe" });
    return r.exitCode === 0 ? r.stdout.toString() : null;
  } catch {
    return null;
  }
};
const get = async (url: string) => (await fetch(url, { signal: AbortSignal.timeout(30_000) })).text();

const linguist = Bun.YAML.parse(await get("https://raw.githubusercontent.com/github-linguist/linguist/main/lib/linguist/languages.yml")) as Record<string, { type: string }>;
const languages = Object.entries(linguist).filter(([, v]) => v.type === "programming").map(([k]) => k).sort();
const cldr = JSON.parse(await get("https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-core/availableLocales.json"));
const locales: string[] = cldr.availableLocales.full;

const rust = sh(["rustc", "--print", "target-list"])?.split("\n").filter(Boolean) ?? null;
const go = sh(["go", "tool", "dist", "list"])?.split("\n").filter(Boolean) ?? null;
const zigJson = sh(["zig", "targets"]);
// zig targets prints ZON (`.libc = .{ "aarch64-linux-gnu", ... }`), not JSON
const zig = zigJson ? [...(zigJson.match(/\.libc\s*=\s*\.\{([\s\S]*?)\}/)?.[1] ?? "").matchAll(/"([^"]+)"/g)].map((m) => m[1]!) : null;
// bun-types of the Bun fork, from the sparse checkout that apps/bun-m3/gen/sources.ts makes in .cache/bun-fork
const typesDir = join(root, ".cache/bun-fork/packages/bun-types");
if (!existsSync(typesDir)) throw new Error(`${typesDir}: missing; run bun apps/bun-m3/gen/sources.ts first`);
const bunTypes = (await Promise.all([...new Bun.Glob("*.d.ts").scanSync({ cwd: typesDir })].map((f) => Bun.file(join(typesDir, f)).text()))).join("\n");
// CompileTarget is a union of template literals over Architecture, SIMD and Libc: expand it
const union = (name: string) => [...(bunTypes.match(new RegExp(`type ${name} = ([^;]+);`))?.[1] ?? "").matchAll(/"([^"]+)"/g)].map((m) => m[1]!);
const vars: Record<string, string[]> = { Architecture: union("Architecture"), SIMD: union("SIMD"), Libc: union("Libc") };
const templates = [...(bunTypes.match(/type CompileTarget =([\s\S]*?);/)?.[1] ?? "").matchAll(/\`([^\`]+)\`/g)].map((m) => m[1]!);
const expand = (tpl: string): string[] => {
  const m = tpl.match(/\$\{(\w+)\}/);
  return m ? (vars[m[1]!] ?? []).flatMap((v) => expand(tpl.replace(m[0], v))) : [tpl];
};
const bunTargets = [...new Set(templates.flatMap(expand))].sort();

const fw = await Bun.file(join(root, "docs/ideas/inventory/frameworks.json")).json().catch(() => ({ records: [] }));
const frameworks = fw.records.length;

const osOf = (t: string) => t.match(/(linux|windows|darwin|macos|ios|android|freebsd|netbsd|openbsd|wasi|wasm|emscripten|fuchsia|haiku|illumos|solaris|aix|uefi|none|redox|hermit|vxworks|nto|horizon|psp|vita|switch|tvos|watchos|visionos)/)?.[1] ?? "other";
const families = (list: string[] | null) => list && Object.fromEntries(Object.entries(list.reduce<Record<string, number>>((a, t) => ((a[osOf(t)] = (a[osOf(t)] ?? 0) + 1), a), {})).sort((a, b) => b[1] - a[1]));

const data = {
  sources: {
    languages: "github-linguist/linguist lib/linguist/languages.yml",
    locales: "unicode-org/cldr-json cldr-core/availableLocales.json (full)",
    rust: "rustc --print target-list", go: "go tool dist list", zig: "zig targets (.libc)", bun: "bun-types CompileTarget",
    frameworks: "docs/ideas/inventory/frameworks.json",
  },
  counts: { languages: languages.length, locales: locales.length, rust: rust?.length ?? "not installed", go: go?.length ?? "not installed", zig: zig?.length ?? "not installed", bun: bunTargets.length, frameworks },
  osFamilies: { rust: families(rust), go: families(go), zig: families(zig) },
  languages, locales, rust, go, zig, bun: bunTargets,
};
await Bun.write(join(root, "docs/ideas/inventory/targets.json"), `${JSON.stringify(data, null, 2)}\n`);
const md = [
  "# Target registry", "",
  "Generated by `bun scripts/inventory/targets.ts`. Every selection (framework, language, OS, architecture, human language) is a rule over these lists, never a hand-picked subset. Data: [targets.json](targets.json).", "",
  "| Dimension | Count | Source |", "|---|---|---|",
  `| Programming languages | ${languages.length} | ${data.sources.languages} |`,
  `| Human languages (locales) | ${locales.length} | ${data.sources.locales} |`,
  `| Rust targets | ${data.counts.rust} | ${data.sources.rust} |`,
  `| Go targets | ${data.counts.go} | ${data.sources.go} |`,
  `| Zig libc targets | ${data.counts.zig} | ${data.sources.zig} |`,
  `| Bun compile targets | ${bunTargets.length} | ${data.sources.bun} |`,
  `| UI frameworks and libraries | ${frameworks} | ${data.sources.frameworks} |`, "",
  "## OS families (Rust targets)", "", "| OS | Targets |", "|---|---|",
  ...Object.entries(data.osFamilies.rust ?? {}).map(([k, v]) => `| ${k} | ${v} |`), "",
];
await Bun.write(join(root, "docs/ideas/inventory/targets.md"), md.join("\n"));

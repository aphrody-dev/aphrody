// Live inventory of the Servo org and the Obscura owner -> .local/docs/inventory.md (private, generated: kept vs skipped, with the reason).
// usage: bun tools/inventory.ts
import { $ } from "bun";
const kept = new Set(
  [
    ...(await Bun.file(new URL("./upstreams.toml", import.meta.url)).text()).matchAll(
      /^url = "https:\/\/github.com\/([^"]+)"/gm,
    ),
  ].map((m) => m[1].toLowerCase()),
);
kept.add("h4ckf0r0day/obscura"); // imported through its aphrody-labs fork
const notes: Record<string, string> = {
  "h4ckf0r0day/obscura-benchmark": "Python benchmark harness, not a crate",
  "servo/tendril": "superseded by the tendril crate inside html5ever",
  "servo/font-kit": "not in the dependency graph of servo 0.8",
  "servo/pathfinder": "not in the dependency graph of servo 0.8",
  "servo/malloc_size_of": "stylo carries its own malloc_size_of",
  "servo/rust-stb-image": "not in the dependency graph of servo 0.8",
  "servo/rustc-test": "test harness, not in the dependency graph",
  "servo/wpt": "fork of web-platform-tests (490 MB), fetched by mach update-wpt",
  "servo/doc.servo.org": "generated rustdoc site",
  "servo/internal-wpt-dashboard": "dashboard website (5 GB)",
  "servo/servo.org": "website",
  "servo/book": "documentation site",
  "servo/ci-runners": "CI infrastructure",
  "servo/actions": "CI infrastructure",
  "servo/project": "governance",
  "servo/highfive": "bot",
  "servo/servo-starters": "contributor index site",
  "servo/servo-nightly-builds": "release publisher",
  "servo/libgstreamer_android_gen": "Android build helper (460 MB)",
  "servo/osmesa-src": "vendored Mesa for CI",
  "servo/release-tests": "dead (2020)",
  "servo/mozjs": "kept",
};

type R = {
  full_name: string;
  archived: boolean;
  fork: boolean;
  size: number;
  language: string | null;
  pushed_at: string;
  stargazers_count: number;
};
const repos: R[] = [];
for (const owner of ["orgs/servo", "users/h4ckf0r0day"]) {
  const out = await $`gh api -X GET ${owner}/repos -F per_page=100 --paginate --slurp`.text();
  for (const page of JSON.parse(out)) repos.push(...page);
}
const rows = repos
  .sort((a, b) => b.pushed_at.localeCompare(a.pushed_at))
  .map((r) => {
    const k = kept.has(r.full_name.toLowerCase());
    const why = k
      ? "kept"
      : r.archived
        ? "archived"
        : (notes[r.full_name.toLowerCase()] ?? (r.fork ? "fork" : "not used"));
    return `| ${r.full_name} | ${r.archived ? "yes" : ""} | ${r.fork ? "yes" : ""} | ${(r.size / 1024).toFixed(1)} | ${r.language ?? ""} | ${r.pushed_at.slice(0, 10)} | ${why} |`;
  });
const text = [
  "# Inventory (generated by tools/inventory.ts, private)\n",
  `${repos.length} repositories; kept ${rows.filter((r) => r.endsWith("| kept |")).length}.\n`,
  "| repo | archived | fork | size MiB | language | last push | decision |\n|---|---|---|---:|---|---|---|",
  rows.join("\n"),
].join("\n");
const out = new URL("../.local/docs/inventory.md", import.meta.url);
await Bun.write(out, text + "\n"); // Bun.write creates the directories
console.log(`${repos.length} repositories -> ${Bun.fileURLToPath(out)}`);

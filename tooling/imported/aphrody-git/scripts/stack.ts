#!/usr/bin/env bun
/**
 * Applies stack.toml: the forks, `.gitmodules`, the gitlinks and the lineage remotes.
 *
 *   bun scripts/stack.ts            # everything below, in order
 *   bun scripts/stack.ts forks      # create missing forks under the owner, sync each with its upstream
 *   bun scripts/stack.ts modules    # write .gitmodules (relative URLs, no `branch`: the gitlinks pin the commits) and add missing submodules
 *   bun scripts/stack.ts pin        # move every gitlink to its fork's branch tip
 *   bun scripts/stack.ts lineage    # add the lineage upstreams as remotes of checked-out submodules
 *   bun scripts/stack.ts status
 *
 * The owner is `STACK_OWNER`, else the owner of this checkout's `origin`. Branches come from the
 * upstream's default branch unless stack.toml names one. Network calls run in parallel.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

interface Repo {
  name: string;
  upstream: string;
  path: string;
  branch?: string;
  lineage?: string[];
  update?: "checkout" | "none";
  role: string;
}

const root = resolve(import.meta.dirname, "..");
const stack = Bun.TOML.parse(readFileSync(join(root, "stack.toml"), "utf8")) as { repo: Repo[] };

async function sh(cmd: string[], cwd = root, ok = false): Promise<string> {
  const p = Bun.spawn(cmd, { cwd, stdin: "ignore", stdout: "pipe", stderr: "pipe" });
  const [out, err, code] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text(), p.exited]);
  if (code !== 0 && !ok) throw new Error(`${cmd.join(" ")}: ${err.trim() || `exit ${code}`}`);
  return code === 0 ? out.trim() : "";
}

async function owner(): Promise<string> {
  if (process.env.STACK_OWNER) return process.env.STACK_OWNER;
  const url = await sh(["git", "remote", "get-url", "origin"]);
  const m = url.match(/github\.com[/:]([^/]+)\//);
  if (!m) throw new Error(`origin ${url} is not on GitHub; set STACK_OWNER`);
  return m[1]!;
}

const branches = new Map<string, string>();
async function branchOf(r: Repo): Promise<string> {
  if (r.branch) return r.branch;
  if (!branches.has(r.upstream)) {
    branches.set(r.upstream, await sh(["gh", "api", `repos/${r.upstream}`, "--jq", ".default_branch"]));
  }
  return branches.get(r.upstream)!;
}

async function forks(org: string): Promise<void> {
  await Promise.all(
    stack.repo.map(async r => {
      const have = await sh(["gh", "api", `repos/${org}/${r.name}`, "--jq", ".parent.full_name // \"\""], root, true);
      if (!have) {
        await sh(["gh", "repo", "fork", r.upstream, "--org", org, "--fork-name", r.name, "--clone=false", "--default-branch-only"]);
        console.log(`forked ${r.upstream} -> ${org}/${r.name}`);
      }
      const branch = await branchOf(r);
      const sync = Bun.spawn(["gh", "repo", "sync", `${org}/${r.name}`, "--source", r.upstream, "--branch", branch], { stdin: "ignore", stdout: "ignore", stderr: "pipe" });
      const [why, code] = await Promise.all([new Response(sync.stderr).text(), sync.exited]);
      console.log(`${org}/${r.name} ${branch} ${code === 0 ? "synced" : `not synced: ${why.trim()}`}`);
    }),
  );
}

async function modules(org: string): Promise<void> {
  const lines = ["# Generated by scripts/stack.ts from stack.toml. Do not edit."];
  for (const r of stack.repo) {
    lines.push(`[submodule "${r.path}"]`, `\tpath = ${r.path}`, `\turl = ../${r.name}.git`);
    lines.push("\tshallow = true");
    if (r.update === "none") lines.push("\tupdate = none");
  }
  writeFileSync(join(root, ".gitmodules"), `${lines.join("\n")}\n`);
  await sh(["git", "add", ".gitmodules"]);
  const staged = new Set((await sh(["git", "ls-files", "-s"])).split("\n").map(l => l.split("\t")[1]));
  // Network in parallel; the index has one writer, so its updates run one after another.
  const fetched = await Promise.all(
    stack.repo
      .filter(r => !staged.has(r.path))
      .map(async r => {
        const branch = await branchOf(r);
        const url = `https://github.com/${org}/${r.name}.git`;
        if (r.update !== "none") {
          await sh(["git", "clone", "-q", "--depth", "1", "--filter=blob:none", "-b", branch, url, r.path]);
          return { r, sha: "" };
        }
        return { r, sha: (await sh(["git", "ls-remote", url, `refs/heads/${branch}`])).split(/\s/)[0]! };
      }),
  );
  for (const { r, sha } of fetched) {
    if (sha) {
      await sh(["git", "update-index", "--add", "--cacheinfo", `160000,${sha},${r.path}`]);
      mkdirSync(join(root, r.path), { recursive: true });
    }
    else {
      await sh(["git", "add", "--", r.path]);
      await sh(["git", "submodule", "absorbgitdirs", "--", r.path], root, true);
    }
    console.log(`added ${r.path}`);
  }
  await sh(["git", "submodule", "init"]);
}

async function pin(org: string): Promise<void> {
  const moved = await Promise.all(
    stack.repo.map(async r => {
      const branch = await branchOf(r);
      const dir = join(root, r.path);
      if (!existsSync(join(dir, ".git"))) {
        const url = `https://github.com/${org}/${r.name}.git`;
        return { r, sha: (await sh(["git", "ls-remote", url, `refs/heads/${branch}`])).split(/\s/)[0]! };
      }
      await sh(["git", "fetch", "-q", "--depth", "1", "origin", branch], dir);
      await sh(["git", "checkout", "-q", "--detach", "FETCH_HEAD"], dir);
      return { r, sha: await sh(["git", "rev-parse", "HEAD"], dir) };
    }),
  );
  for (const { r, sha } of moved) {
    await sh(["git", "update-index", "--add", "--cacheinfo", `160000,${sha},${r.path}`]);
    console.log(`${r.path} ${sha.slice(0, 12)}`);
  }
}

async function lineage(): Promise<void> {
  for (const r of stack.repo) {
    const dir = join(root, r.path);
    if (!existsSync(join(dir, ".git"))) continue;
    for (const up of [r.upstream, ...(r.lineage ?? [])]) {
      const name = up.split("/")[0]!;
      const have = await sh(["git", "remote", "get-url", name], dir, true);
      if (!have) await sh(["git", "remote", "add", name, `https://github.com/${up}.git`], dir);
    }
  }
}

async function status(): Promise<void> {
  console.log(await sh(["git", "submodule", "status"], root, true));
}

const org = await owner();
const step = process.argv[2] ?? "all";
const steps: Record<string, () => Promise<void>> = {
  forks: () => forks(org),
  modules: () => modules(org),
  pin: () => pin(org),
  lineage,
  status,
};
if (step === "all") {
  for (const s of ["forks", "modules", "lineage", "status"]) await steps[s]!();
} else if (steps[step]) {
  await steps[step]();
} else {
  console.error(`unknown step ${step}; one of all, ${Object.keys(steps).join(", ")}`);
  process.exit(2);
}

#!/usr/bin/env bun
// Measures how a maintainer lands pull requests, from the public GitHub API (read only). Used for the Bun rows of docs/standards/code-style.md.
// Usage: bun tools/bun-practice.ts [--repo=oven-sh/bun] [--author=Jarred-Sumner] [--limit=100] [--json]
// Output: counts for title shape, body structure, diff size, tests attached, squash-message shape and review traffic, plus a sha256 of the PR set.
const arg = (k: string, d: string) => process.argv.find((a) => a.startsWith(`--${k}=`))?.split("=")[1] ?? d;
const repo = arg("repo", "oven-sh/bun");
const author = arg("author", "Jarred-Sumner");
const limit = Number(arg("limit", "100"));

async function gh(...a: string[]): Promise<any> {
  const p = Bun.spawn(["gh", ...a], { stdout: "pipe", stderr: "pipe" });
  const text = await new Response(p.stdout).text();
  await p.exited;
  try { return JSON.parse(text); } catch { return null; }
}

let prs: any[] | null = null;
for (let i = 0; i < 4 && !prs; i++) {
  prs = await gh("pr", "list", "-R", repo, "--author", author, "--state", "merged", "--limit", String(limit), "--json", "number,title,body,additions,deletions,changedFiles,mergedAt,labels,mergeCommit");
  if (!prs) await Bun.sleep(3000);
}
if (!prs) throw new Error("gh pr list failed");

type Extra = { msg: string; testFiles: number; inlineByAuthor: number; inlineByOthers: number; reviewByOthers: number };
const extras = new Map<number, Extra>();
const queue = [...prs];
await Promise.all(Array.from({ length: 6 }, async () => {
  while (queue.length) {
    const p = queue.shift()!;
    const commit = p.mergeCommit?.oid ? await gh("api", `repos/${repo}/commits/${p.mergeCommit.oid}`) : null;
    let testFiles = -1;
    if (p.changedFiles <= 300) {
      const files: any[] = [];
      for (let pg = 1; pg <= 3; pg++) {
        const f = await gh("api", `repos/${repo}/pulls/${p.number}/files?per_page=100&page=${pg}`);
        if (!Array.isArray(f)) break;
        files.push(...f);
        if (f.length < 100) break;
      }
      testFiles = files.filter((f) => /^tests?\//.test(f.filename)).length;
    }
    const inline = (await gh("api", `repos/${repo}/pulls/${p.number}/comments?per_page=100`)) ?? [];
    const reviews = (await gh("api", `repos/${repo}/pulls/${p.number}/reviews?per_page=100`)) ?? [];
    extras.set(p.number, {
      msg: commit?.commit?.message ?? "", testFiles,
      inlineByAuthor: inline.filter((c: any) => c.user?.login === author).length,
      inlineByOthers: inline.filter((c: any) => c.user?.login !== author).length,
      reviewByOthers: reviews.filter((r: any) => r.user?.login !== author).length,
    });
  }
}));

const med = (x: number[]) => [...x].sort((p, q) => p - q)[Math.floor(x.length / 2)]!;
const count = (xs: any[], f: (x: any) => boolean) => xs.filter(f).length;
const titles: string[] = prs.map((p) => p.title);
const lens = titles.map((t) => t.length);
const prefixCounts = new Map<string, number>();
for (const t of titles) {
  const m = /^([A-Za-z0-9_.\-/`]+(?:\([^)]*\))?)[:!]\s/.exec(t);
  if (m) prefixCounts.set(m[1]!.replace(/\(.*\)/, "(...)"), (prefixCounts.get(m[1]!.replace(/\(.*\)/, "(...)")) ?? 0) + 1);
}
const sizes = prs.map((p) => p.additions + p.deletions);
const small = prs.filter((p) => p.changedFiles <= 300);
const bodies: string[] = prs.map((p) => p.body ?? "");
const has = (re: RegExp) => count(bodies, (b) => re.test(b));
const subjects = [...extras.values()].map((e) => e.msg.split("\n")[0]!);
const out = {
  repo, author, n: prs.length, window: [prs.at(-1).mergedAt, prs[0].mergedAt],
  setSha256: new Bun.CryptoHasher("sha256").update(prs.map((p) => `${p.number}:${p.mergeCommit?.oid}`).sort().join("\n")).digest("hex"),
  title: { medianChars: med(lens), over72: count(lens, (l) => l > 72), areaPrefix: [...prefixCounts.values()].reduce((a, b) => a + b, 0), conventionalType: count(titles, (t) => /^(feat|fix|docs|chore|refactor|perf|test|build|ci|revert)(\(.+\))?!?:/.test(t)), endsWithPeriod: count(titles, (t) => t.endsWith(".")), topPrefixes: [...prefixCounts].sort((a, b) => b[1] - a[1]).slice(0, 8) },
  size: { medianChangedLines: med(sizes), over1000Lines: count(sizes, (s) => s > 1000), upTo100Lines: count(sizes, (s) => s <= 100), medianFiles: med(prs.map((p) => p.changedFiles)) },
  body: { empty: has(/^\s*$/), medianChars: med(bodies.map((b) => b.length)), templateWhat: has(/What does this PR do/i), templateVerify: has(/How did you verify/i), closesIssue: has(/\b(fix(es)?|close[sd]?|resolve[sd]?)\s+#\d+/i), mentionsTest: has(/\btests?\b/i), failsOnUnfixed: has(/USE_SYSTEM_BUN|fail(s|ed)? (on|before|without)|unfixed/i), hasNumbers: has(/\d+(\.\d+)?\s?(ms|us|MB|x faster)\b/), tables: has(/^\|.*\|$/m), generatedFooter: has(/Generated by .*Claude/i) },
  tests: { prsUpTo300Files: small.length, withTestFiles: count(small, (p) => (extras.get(p.number)?.testFiles ?? 0) > 0), withoutTestFiles: count(small, (p) => extras.get(p.number)?.testFiles === 0), withoutTestNumbers: small.filter((p) => extras.get(p.number)?.testFiles === 0).map((p) => p.number) },
  squash: { subjectEndsWithPrNumber: count(subjects, (s) => /\(#\d+\)$/.test(s)), bodyPresent: count([...extras.values()], (e) => e.msg.includes("\n\n")), coAuthoredTrailers: count([...extras.values()], (e) => /^co-authored-by:/im.test(e.msg)), signedOffBy: count([...extras.values()], (e) => /^signed-off-by:/im.test(e.msg)) },
  review: { inlineByAuthor: [...extras.values()].reduce((s, e) => s + e.inlineByAuthor, 0), inlineByOthers: [...extras.values()].reduce((s, e) => s + e.inlineByOthers, 0), reviewsByOthers: [...extras.values()].reduce((s, e) => s + e.reviewByOthers, 0) },
};
console.log(process.argv.includes("--json") ? JSON.stringify(out) : JSON.stringify(out, null, 2));

#!/usr/bin/env bun
// Fetches every source of the unified code standard and records where it came from: resolved revision, retrieval date,
// sha256 and byte size of the fetched bytes. Reading only: nothing is written to any upstream.
//
// Usage:
//   bun tools/standards-sources.ts check [root]            validate docs/standards/sources.toml (shape, hashes well formed); exit 1 on error
//   bun tools/standards-sources.ts refresh [--only=id,id]  fetch live, rewrite sources.toml; --cache=<dir> keeps the fetched bytes
//   bun tools/standards-sources.ts verify                  fetch live and report which recorded hashes drifted (exit 0 even on drift: pages change)
// Source kinds:
//   github  repo + path + ref   resolved to a commit with `gh api`, bytes from raw.githubusercontent.com at that commit
//   gitiles repo(url base) + path + ref   Chromium Gitiles: <base>/+/<ref>/<path>?format=TEXT (base64)
//   url     url                 plain HTTPS GET of the page, bytes hashed as served
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { mkdirSync } from "node:fs";

type Source = {
  id: string; title: string; kind: "github" | "gitiles" | "url"; url: string;
  repo?: string; path?: string; ref?: string; rev?: string; retrieved?: string; sha256?: string; size?: number; sections?: string[]; use?: string;
};

const mode = process.argv[2] ?? "check";
const args = new Map<string, string>();
for (const a of process.argv.slice(3)) { const m = /^--([^=]+)(?:=(.*))?$/.exec(a); if (m) args.set(m[1]!, m[2] ?? "true"); }
const root = resolve(process.argv.slice(3).find((a) => !a.startsWith("--")) ?? join(import.meta.dir, ".."));
const file = join(root, "docs/standards/sources.toml");
const doc = Bun.TOML.parse(await Bun.file(file).text()) as { meta: Record<string, string>; tags?: Record<string, string[]>; source: Source[]; measurement?: Record<string, unknown>[] };

const sha256 = (b: Uint8Array) => new Bun.CryptoHasher("sha256").update(b).digest("hex");
const gh = async (path: string) => (await Bun.$`gh api ${path} --jq .sha`.quiet().text()).trim();

async function fetchBytes(s: Source): Promise<{ bytes: Uint8Array; rev?: string }> {
  if (s.kind === "github") {
    const rev = await gh(`repos/${s.repo}/commits/${s.ref ?? "HEAD"}`);
    const res = await fetch(`https://raw.githubusercontent.com/${s.repo}/${rev}/${s.path}`);
    if (!res.ok) throw new Error(`${s.id}: ${res.status} ${res.url}`);
    return { bytes: new Uint8Array(await res.arrayBuffer()), rev };
  }
  if (s.kind === "gitiles") {
    const res = await fetch(`${s.repo}/+/${s.ref ?? "main"}/${s.path}?format=TEXT`);
    if (!res.ok) throw new Error(`${s.id}: ${res.status} ${res.url}`);
    return { bytes: Uint8Array.from(Buffer.from(await res.text(), "base64")) };
  }
  const res = await fetch(s.url, { headers: { "user-agent": "aphrody-standards-sources" } });
  if (!res.ok) throw new Error(`${s.id}: ${res.status} ${s.url}`);
  return { bytes: new Uint8Array(await res.arrayBuffer()) };
}

function toml(d: typeof doc): string {
  const q = (v: unknown) => (Array.isArray(v) ? `[${v.map(q).join(", ")}]` : typeof v === "number" ? String(v) : JSON.stringify(v));
  const block = (head: string, o: Record<string, unknown>) => `[[${head}]]\n${Object.entries(o).filter(([, v]) => v !== undefined).map(([k, v]) => `${k} = ${q(v)}`).join("\n")}\n`;
  const meta = `[meta]\n${Object.entries(d.meta).map(([k, v]) => `${k} = ${q(v)}`).join("\n")}\n`;
  const tags = d.tags ? `\n[tags]\n${Object.entries(d.tags).map(([k, v]) => `${k} = ${q(v)}`).join("\n")}\n` : "";
  const header = "# Sources of docs/standards/code-style.md. Generated by tools/standards-sources.ts; edit only id, title, kind and locator fields by hand, then run refresh.\n# sha256 and size describe the fetched bytes (decoded text for gitiles). rev is the resolved commit for github sources.\n";
  return [header + meta + tags, ...d.source.map((s) => block("source", s as unknown as Record<string, unknown>)), ...(d.measurement ?? []).map((m) => block("measurement", m))].join("\n");
}

const errors: string[] = [];
const ids = new Set<string>();
for (const s of doc.source) {
  if (ids.has(s.id)) errors.push(`duplicate id ${s.id}`);
  ids.add(s.id);
  if (!/^[a-z0-9][a-z0-9-]*$/.test(s.id)) errors.push(`${s.id}: id must be lowercase kebab`);
  if (!/^https:\/\//.test(s.url)) errors.push(`${s.id}: url must be https`);
  if (s.kind === "github" && !(s.repo && s.path)) errors.push(`${s.id}: github needs repo and path`);
  if (s.kind === "gitiles" && !(s.repo && s.path)) errors.push(`${s.id}: gitiles needs repo and path`);
}

if (mode === "check") {
  for (const s of doc.source) {
    if (!/^[0-9a-f]{64}$/.test(s.sha256 ?? "")) errors.push(`${s.id}: sha256 missing or malformed (run refresh)`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(s.retrieved ?? "")) errors.push(`${s.id}: retrieved missing`);
    if (!(s.size && s.size > 0)) errors.push(`${s.id}: size missing`);
    if (s.kind === "github" && !/^[0-9a-f]{40}$/.test(s.rev ?? "")) errors.push(`${s.id}: rev missing`);
  }
  const mids = new Set((doc.measurement ?? []).map((m) => m.id as string));
  for (const [tag, refs] of Object.entries(doc.tags ?? {})) for (const r of refs) if (!(r.startsWith("measurement:") ? mids.has(r.slice(12)) : ids.has(r))) errors.push(`tag ${tag}: unknown source ${r}`);
  const tagged = new Set(Object.values(doc.tags ?? {}).flat());
  for (const s of doc.source) if (!tagged.has(s.id)) errors.push(`${s.id}: not covered by any tag`);
  for (const e of errors) console.error(`error: ${e}`);
  console.log(`${doc.source.length} sources, ${errors.length} errors`);
  process.exit(errors.length ? 1 : 0);
}

if (errors.length) { for (const e of errors) console.error(`error: ${e}`); process.exit(1); }
const only = args.get("only")?.split(",");
const cache = args.get("cache") ?? join(tmpdir(), "aphrody-standards-sources");
mkdirSync(cache, { recursive: true });
const today = new Date().toISOString().slice(0, 10);
const todo = doc.source.filter((s) => !only || only.includes(s.id));
let drift = 0;
const queue = [...todo];
await Promise.all(Array.from({ length: 6 }, async () => {
  while (queue.length) {
    const s = queue.shift()!;
    const { bytes, rev } = await fetchBytes(s);
    await Bun.write(join(cache, s.id), bytes);
    const h = sha256(bytes);
    if (mode === "verify") {
      if (h !== s.sha256) { drift++; console.log(`drift ${s.id}: recorded ${s.sha256?.slice(0, 12)} live ${h.slice(0, 12)}`); }
      continue;
    }
    Object.assign(s, { rev, retrieved: today, sha256: h, size: bytes.length });
    if (!rev) delete s.rev;
    else s.url = `https://github.com/${s.repo}/blob/${rev}/${s.path}`;
    console.log(`${s.id} ${bytes.length} ${h.slice(0, 12)}`);
  }
}));
if (mode === "refresh") {
  doc.meta.retrieved = today;
  await Bun.write(file, toml(doc));
  console.log(`wrote ${file}; fetched bytes cached in ${cache}`);
} else console.log(`${drift} of ${todo.length} drifted`);
